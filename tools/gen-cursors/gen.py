#!/usr/bin/env python
"""Generates pkg/cursor/table_gen.go from OpenLoco's Ui.h (the CursorId enum),
Ui.cpp (initialiseCursors: which id is an SDL system cursor, which one of
Cursor.cpp's bitmaps) and Ui/Cursor.cpp (each bitmap: its hot spot and 32 rows
of 'X' black, '.' white, ' ' transparent).

    python tools/gen-cursors/gen.py ~/Projects/OpenLoco > pkg/cursor/table_gen.go
"""
import os, re, sys

up = sys.argv[1]
src = os.path.join(up, "src/OpenLoco")
hdr = open(os.path.join(src, "include/OpenLoco/Ui.h")).read()
ui = open(os.path.join(src, "src/Ui.cpp")).read()
cur = open(os.path.join(src, "src/Ui/Cursor.cpp")).read()

enum = re.search(r"enum class CursorId : uint8_t\s*\{(.*?)\};", hdr, re.S).group(1)
ids = [n.strip() for n in enum.split(",") if n.strip()]
count = int(re.search(r"constexpr uint8_t kNumCursors = (\d+);", hdr).group(1))
assert len(ids) == count, (len(ids), count)

init = re.search(r"void initialiseCursors\(\)\s*\{(.*?)\n    \}", ui, re.S).group(1)
system = dict(re.findall(r"loadSystemCursor\(CursorId::(\w+), (SDL_SYSTEM_CURSOR_\w+)\);", init))
bitmap = dict(re.findall(r"loadCursor\(CursorId::(\w+), Cursor::(\w+)\);", init))
assert set(system) | set(bitmap) == set(ids), set(ids) ^ (set(system) | set(bitmap))

bitmaps = {}
for m in re.finditer(r"Cursor Cursor::(\w+) = Cursor\(\s*(\d+), (\d+),((?:\s*\"[^\"]*\")+)\s*\);", cur):
    rows = re.findall(r"\"([^\"]*)\"", m.group(4))
    assert len(rows) == 32 and all(len(r) == 32 for r in rows), m.group(1)
    bitmaps[m.group(1)] = (int(m.group(2)), int(m.group(3)), rows)

def ident(s):
    return s[0].upper() + s[1:]

print("// Code generated by tools/gen-cursors/gen.py from OpenLoco's Ui.h, Ui.cpp")
print("// (initialiseCursors) and Ui/Cursor.cpp. DO NOT EDIT.")
print()
print("package cursor")
print()
print("// The CursorId enum (Ui.h), in its order.")
print("const (")
for i, n in enumerate(ids):
    print("\t%s%s" % (ident(n), " Id = iota" if i == 0 else ""))
print("\tCount")
print(")")
print()
print("// table is initialiseCursors: an SDL system cursor (loadSystemCursor) or a")
print("// 32x32 bitmap of Cursor.cpp (loadCursor: SDL_CreateCursor with its hot spot).")
print("var table = [Count]def{")
for n in ids:
    if n in system:
        print("\t%s: {system: %s}," % (ident(n), "\"" + system[n] + "\""))
        continue
    x, y, rows = bitmaps[bitmap[n]]
    print("\t%s: {hotX: %d, hotY: %d, rows: [32]string{" % (ident(n), x, y))
    for r in rows:
        print("\t\t%s," % ('"' + r + '"'))
    print("\t}},")
print("}")

#!/usr/bin/env python
"""Generates pkg/shortcuts/table_gen.go from OpenLoco's Input/Shortcuts.h (the
Shortcut enum), Input/Shortcuts.cpp (initialize(): each shortcut's string id,
config name and default binding) and SDL3's own key names (sdlkeys.c, built
against the installed SDL3: SDL_GetKeyFromScancode / SDL_GetKeyName).

    python tools/gen-shortcuts/gen.py ~/Projects/OpenLoco > pkg/shortcuts/table_gen.go
"""
import os, re, subprocess, sys, tempfile

up = sys.argv[1]
here = os.path.dirname(os.path.abspath(__file__))
hdr = open(os.path.join(up, "src/OpenLoco/include/OpenLoco/Input/Shortcuts.h")).read()
cpp = open(os.path.join(up, "src/OpenLoco/src/Input/Shortcuts.cpp")).read()
sids = dict((m.group(1), int(m.group(2))) for m in re.finditer(r"constexpr StringId (\w+) = (\d+);",
    open(os.path.join(up, "src/OpenLoco/include/OpenLoco/Localisation/StringIds.h")).read()))

enum = re.search(r"enum class Shortcut : uint32_t\s*\{(.*?)\};", hdr, re.S).group(1)
ids = [n.strip() for n in enum.split(",") if n.strip()]
adds = {}
for m in re.finditer(r'ShortcutManager::add\(Shortcut::(\w+),\s*StringIds::(\w+),\s*(\w+),\s*"([^"]*)",\s*"([^"]*)"\);', cpp):
    adds[m.group(1)] = (m.group(2), m.group(4), m.group(5))
assert set(adds) == set(ids), set(ids) ^ set(adds)

with tempfile.TemporaryDirectory() as d:
    exe = os.path.join(d, "sdlkeys")
    flags = subprocess.check_output(["pkg-config", "--cflags", "--libs", "sdl3"], text=True).split()
    subprocess.check_call(["gcc", os.path.join(here, "sdlkeys.c"), "-o", exe] + flags)
    keys = [l.split("\t") for l in subprocess.check_output([exe], text=True).splitlines()]

def go(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

def ident(s):
    return s[0].upper() + s[1:]

print("// Code generated by tools/gen-shortcuts/gen.py from OpenLoco's Input/Shortcuts.h,")
print("// Input/Shortcuts.cpp and SDL3's key names. DO NOT EDIT.")
print()
print("package shortcuts")
print()
print("// The Shortcut enum (Shortcuts.h), in its order: ShortcutManager's list is")
print("// sorted by it.")
print("const (")
for i, n in enumerate(ids):
    print("\t%s%s" % (ident(n), " Shortcut = iota" if i == 0 else ""))
print("\tCount")
print(")")
print()
print("// Defs is ShortcutManager::getList() after Shortcuts::initialize: each")
print("// shortcut's display string (StringIds: its name and id), config name and default binding.")
print("var Defs = [Count]Def{")
for n in ids:
    sid, cfg, default = adds[n]
    print("\t{%s, %s, %d, %s, %s}," % (ident(n), go(sid), sids[sid], go(cfg), go(default)))
print("}")
print()
print("// sdlKeys: SDL3's keycode of each scancode (no modifiers) with")
print("// SDL_GetKeyName's name for it, in scancode order.")
print("var sdlKeys = [...]struct {")
print("\tCode     uint32")
print("\tScancode uint16")
print("\tName     string")
print("}{")
for code, sc, name, _ in keys:
    print("\t{%s, %s, %s}," % (code, sc, go(name)))
print("}")

// gen_subposition.cpp — prints Map/Track/SubpositionData.cpp's movement
// tables (getTrackSubPositon, getRoadSubPositon for both traffic sides,
// getRoadPlacementSubPositon) as Go. The .cpp is included so its static
// arrays can be read directly.
#include "Map/Track/SubpositionData.cpp"
#include <cstdio>

namespace OpenLoco
{
    static GameState* _stubState;
    GameState& getGameState() { return *_stubState; } // only referenced by getRoadSubPositon
}

using namespace OpenLoco::World::TrackData;

// spans prints a flat list of spans: Go MoveInfo entries plus per-span offsets.
template<typename C>
static void spans(const char* name, const C& c)
{
    std::printf("// %s: %zu sequences.\nvar %s = [][]MoveInfo{\n", name, std::size(c), name);
    for (const auto& s : c)
    {
        std::printf("\t{");
        for (const auto& m : s)
            std::printf("{%d, %d, %d, %u, %u}, ", m.loc.x, m.loc.y, m.loc.z, m.yaw, (unsigned)m.pitch);
        std::printf("},\n");
    }
    std::printf("}\n\n");
}

int main()
{
    std::printf("// Code generated by tools/gen-paintdata from OpenLoco src/Map/Track/SubpositionData.cpp. DO NOT EDIT.\n\n");
    std::printf("package sim\n\n");
    std::printf("// MoveInfo is TrackData::MoveInfo: a sub-position (x, y, z), yaw and pitch.\n");
    std::printf("type MoveInfo struct {\n\tX, Y, Z int16\n\tYaw, Pitch uint8\n}\n\n");
    spans("TrackSubPositions", _4D9724);
    // _4D9DE4[a][b][i] for (trackAndDirection & 1<<8, & 1<<7, & 0x7F), flattened in that order.
    std::vector<std::span<const MoveInfo>> left, right;
    for (auto& a : _4D9DE4) for (auto& b : a) for (auto& s : b) left.push_back(s);
    for (auto& a : _rightHand4D9DE4) for (auto& b : a) for (auto& s : b) right.push_back(s);
    spans("RoadSubPositionsLeft", left);
    spans("RoadSubPositionsRight", right);
    spans("RoadPlacementSubPositions", kRoadPlacementSubPositions);
}

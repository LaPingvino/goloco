// gen_messagetypes.cpp — prints Message.cpp's _messageTypeDescriptors (via
// getMessageTypeDescriptor) as Go: criticality, sound, flags, argument types,
// duration (days) and priority per MessageType.
#include "Message.h"
#include <cstdio>

using namespace OpenLoco;

int main()
{
    std::printf("// Code generated by tools/gen-paintdata from OpenLoco src/Message.cpp. DO NOT EDIT.\n\n");
    std::printf("package sim\n\n");
    std::printf("// MessageTypeDescriptor is Message.h's MessageTypeDescriptor.\n");
    std::printf("type MessageTypeDescriptor struct {\n\tCriticality, Sound uint8\n\tFlags uint16\n\tArgumentTypes [3]uint8\n\tDuration uint16\n\tPriority uint8\n}\n\n");
    std::printf("// MessageTypeDescriptors is _messageTypeDescriptors (0x004F8BE4…), by MessageType.\n");
    std::printf("var MessageTypeDescriptors = [31]MessageTypeDescriptor{\n");
    for (int i = 0; i < 31; i++)
    {
        const auto& d = getMessageTypeDescriptor(static_cast<MessageType>(i));
        std::printf("\t{%u, %u, 0x%04X, [3]uint8{%u, %u, %u}, %u, %u},\n", (unsigned)d.criticality, (unsigned)d.sound, (unsigned)d.flags,
                    (unsigned)d.argumentTypes[0], (unsigned)d.argumentTypes[1], (unsigned)d.argumentTypes[2], (unsigned)d.duration, (unsigned)d.priority);
    }
    std::printf("}\n");
}

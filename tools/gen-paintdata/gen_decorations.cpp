// gen_decorations.cpp — prints PaintTileDecorations.cpp's tables as Go: the
// height marker images and the track / road decoration height offsets. The
// .cpp is included whole; its functions are removed by the linker.
#include "../../../OpenLoco/src/OpenLoco/src/Paint/PaintTileDecorations.cpp"
#include <cstdio>

int main()
{
    using namespace OpenLoco::Paint;
    std::printf("// Code generated by tools/gen-paintdata/gen.sh from OpenLoco src/Paint/PaintTileDecorations.cpp, PaintRoad.cpp, PaintSignal.cpp. DO NOT EDIT.\n\npackage paint\n\n");
    std::printf("// HeightMarkerImages is kHeightMarkerImages [Config::heightMarkerOffset: units, imperial, metric][height + 128].\nvar HeightMarkerImages = [3][256]uint32{\n");
    for (auto& row : kHeightMarkerImages)
    {
        std::printf("\t{");
        for (auto v : row)
            std::printf("%u, ", (unsigned)v);
        std::printf("},\n");
    }
    std::printf("}\n\n// TrackDecorationHeightOffsets is kTrackDecorationHeightOffsets [trackId]{firstTile, lastTile}.\nvar TrackDecorationHeightOffsets = [%zu][2]int8{", kTrackDecorationHeightOffsets.size());
    for (auto& o : kTrackDecorationHeightOffsets)
        std::printf("{%d, %d}, ", (int)o.firstTile, (int)o.lastTile);
    std::printf("}\n\n// RoadDecorationHeightOffsets is kRoadDecorationHeightOffsets [roadId]{firstTile, lastTile}.\nvar RoadDecorationHeightOffsets = [%zu][2]int8{", kRoadDecorationHeightOffsets.size());
    for (auto& o : kRoadDecorationHeightOffsets)
        std::printf("{%d, %d}, ", (int)o.firstTile, (int)o.lastTile);
    std::printf("}\n");
}

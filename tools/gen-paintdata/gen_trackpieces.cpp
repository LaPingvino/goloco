// gen_trackpieces.cpp — prints TrackData::getTrackPiece / getRoadPiece
// (PreviewTrack: index, x, y, z, clearZ, connectFlags by rotation) and
// World::kRotationOffset / kReverseRotation as Go.
#include "Map/Track/TrackData.h"
#include "Map/Tile.h"
#include <cstdio>

using namespace OpenLoco::World;
using namespace OpenLoco::World::TrackData;

template<typename F>
static void pieces(const char* name, F get, int n)
{
    std::printf("var %s = [%d][]PreviewTrack{\n", name, n);
    for (int i = 0; i < n; i++)
    {
        std::printf("\t{");
        for (const auto& p : get(i))
            std::printf("{%u, %d, %d, %d, %u, [4]uint8{%u, %u, %u, %u}}, ", p.index, p.x, p.y, p.z, p.clearZ,
                        p.connectFlags[0], p.connectFlags[1], p.connectFlags[2], p.connectFlags[3]);
        std::printf("},\n");
    }
    std::printf("}\n\n");
}

int main()
{
    std::printf("// Code generated by tools/gen-paintdata from OpenLoco src/Map/Track/TrackData.cpp. DO NOT EDIT.\n\n");
    std::printf("package sim\n\n");
    std::printf("// PreviewTrack is TrackData::PreviewTrack (index, offset at rotation 0,\n// clearZ in bigZ, connectFlags by rotation).\n");
    std::printf("type PreviewTrack struct {\n\tIndex        uint8\n\tX, Y, Z      int16\n\tClearZ       uint8\n\tConnectFlags [4]uint8\n}\n\n");
    std::printf("// TrackPieces is getTrackPiece, by track id.\n");
    pieces("TrackPieces", [](int i) { return getTrackPiece(i); }, 44);
    std::printf("// RoadPieces is getRoadPiece, by road id.\n");
    pieces("RoadPieces", [](int i) { return getRoadPiece(i); }, 10);
    std::printf("// RotationOffset is World::kRotationOffset.\nvar RotationOffset = [16][2]int16{");
    for (auto& p : kRotationOffset) std::printf("{%d, %d}, ", p.x, p.y);
    std::printf("}\n\n// ReverseRotation is World::kReverseRotation.\nvar ReverseRotation = [16]uint8{");
    for (auto r : kReverseRotation) std::printf("%u, ", r);
    std::printf("}\n\n// TrackCurveSpeedFraction is getTrackMiscData(id).curveSpeedFraction.\nvar TrackCurveSpeedFraction = [44]uint16{");
    for (int i = 0; i < 44; i++) std::printf("%u, ", getTrackMiscData(i).curveSpeedFraction);
    std::printf("}\n\n// RoadCurveSpeedFraction is getRoadMiscData(id).curveSpeedFraction.\nvar RoadCurveSpeedFraction = [10]uint16{");
    for (int i = 0; i < 10; i++) std::printf("%u, ", getRoadMiscData(i).curveSpeedFraction);
    std::printf("}\n\n// RoadReverseLane is getRoadMiscData(id).reverseLane.\nvar RoadReverseLane = [10]uint8{");
    for (int i = 0; i < 10; i++) std::printf("%u, ", getRoadMiscData(i).reverseLane);
    std::printf("}\n\n// RoadOccupationMasks is getRoadOccupationMask (kRoadOccupationMasks).\nvar RoadOccupationMasks = [128]uint8{");
    for (int i = 0; i < 128; i++) std::printf("%u, ", getRoadOccupationMask(i));
    std::printf("}\n");
}

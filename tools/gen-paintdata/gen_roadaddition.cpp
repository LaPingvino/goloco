// gen_roadaddition.cpp — prints PaintRoadAdditionsData.h's
// AdditionStyle1::kRoadPaintAdditionParts (with supports) as Go.
#include "Paint/PaintRoadAdditionsData.h"
#include <cstdio>
#include <type_traits>

using namespace OpenLoco;
using namespace OpenLoco::Paint::AdditionStyle1;

static void pos(const std::array<World::Pos3, 4>& a)
{
    std::printf("[4]Pos3{");
    for (auto& p : a)
        std::printf("{%d, %d, %d}, ", p.x, p.y, p.z);
    std::printf("}");
}

int main()
{
    std::printf("// Code generated by tools/gen-paintdata from OpenLoco include/OpenLoco/Paint/PaintRoadAdditionsData.h. DO NOT EDIT.\n\n");
    std::printf("package paint\n\n");
    std::printf("// RoadAdditionSupport is AdditionStyle1::RoadAdditionSupport (a road extra's support).\n");
    std::printf("type RoadAdditionSupport struct {\n\tImageIDs [4][4]uint32\n\tHeight int16\n\tFrequencies [4]uint8\n\tSegments [4]uint16\n}\n\n");
    std::printf("// RoadAdditionPiece is RoadPaintAdditionPiece.\n");
    std::printf("type RoadAdditionPiece struct {\n\tImageIDs [4]uint32\n\tBBOffsets, BBSizes [4]Pos3\n\tIsMergeable bool\n\tSupports *RoadAdditionSupport\n}\n\n");
    std::printf("// RoadAdditionParts is AdditionStyle1::kRoadPaintAdditionParts [roadId][sequenceIndex].\n");
    std::printf("var RoadAdditionParts = [%zu][]RoadAdditionPiece{\n", kRoadPaintAdditionParts.size());
    for (size_t r = 0; r < kRoadPaintAdditionParts.size(); r++)
    {
        std::printf("\t// roadId %zu\n\t{\n", r);
        for (const auto& p : kRoadPaintAdditionParts[r])
        {
            std::printf("\t\t{ImageIDs: [4]uint32{%u, %u, %u, %u}, BBOffsets: ", p.imageIds[0], p.imageIds[1], p.imageIds[2], p.imageIds[3]);
            pos(p.boundingBoxOffsets);
            std::printf(", BBSizes: ");
            pos(p.boundingBoxSizes);
            std::printf(", IsMergeable: %s", p.isIsMergeable ? "true" : "false");
            if (p.supports.has_value())
            {
                const auto& s = *p.supports;
                std::printf(", Supports: &RoadAdditionSupport{ImageIDs: [4][4]uint32{");
                for (auto& im : s.imageIds)
                    std::printf("{%u, %u, %u, %u}, ", im[0], im[1], im[2], im[3]);
                std::printf("}, Height: %d, Frequencies: [4]uint8{%u, %u, %u, %u}, Segments: [4]uint16{", s.height, s.frequencies[0], s.frequencies[1], s.frequencies[2], s.frequencies[3]);
                for (auto& sg : s.segments)
                    std::printf("%u, ", (unsigned)static_cast<std::underlying_type_t<std::decay_t<decltype(sg)>>>(sg));
                std::printf("}}");
            }
            std::printf("},\n");
        }
        std::printf("\t},\n");
    }
    std::printf("}\n");
}

// gen_trackaddition.cpp — prints PaintTrackAdditionsData.h's
// kTrackPaintAdditionParts (Style0, Style1 with its supports) as Go.
#include "Paint/PaintTrackAdditionsData.h"
#include <cstdio>
#include <type_traits>

using namespace OpenLoco;
using namespace OpenLoco::Paint;

template<typename A>
static void arr(const A& a)
{
    std::printf("{");
    for (auto& v : a)
        std::printf("%lld, ", (long long)v);
    std::printf("}");
}

static void pos(const std::array<World::Pos3, 4>& a)
{
    std::printf("[4]Pos3{");
    for (auto& p : a)
        std::printf("{%d, %d, %d}, ", p.x, p.y, p.z);
    std::printf("}");
}

template<typename P>
static void piece(const P& p)
{
    std::printf("\t\t{ImageIDs: [4]uint32");
    arr(p.imageIds);
    std::printf(", BBOffsets: ");
    pos(p.boundingBoxOffsets);
    std::printf(", BBSizes: ");
    pos(p.boundingBoxSizes);
    std::printf(", IsMergeable: %s", p.isIsMergeable ? "true" : "false");
    if constexpr (requires { p.supports; })
    {
        if (p.supports.has_value())
        {
            const auto& s = *p.supports;
            std::printf(", Supports: &TrackAdditionSupport{ImageIDs: [4][2]uint32{");
            for (auto& im : s.imageIds)
                std::printf("{%u, %u}, ", im[0], im[1]);
            std::printf("}, Height: %d, Frequencies: [4]uint8", s.height);
            arr(s.frequencies);
            std::printf(", Segments: [4]uint16{");
            for (auto& sg : s.segments)
                std::printf("%u, ", (unsigned)static_cast<std::underlying_type_t<std::decay_t<decltype(sg)>>>(sg));
            std::printf("}}");
        }
    }
    std::printf("},\n");
}

template<typename T>
static void table(const char* name, const T& t)
{
    std::printf("var %s = [%zu][]TrackAdditionPiece{\n", name, t.size());
    for (size_t r = 0; r < t.size(); r++)
    {
        std::printf("\t// trackId %zu\n\t{\n", r);
        for (const auto& p : t[r])
            piece(p);
        std::printf("\t},\n");
    }
    std::printf("}\n\n");
}

int main()
{
    std::printf("// Code generated by tools/gen-paintdata from OpenLoco include/OpenLoco/Paint/PaintTrackAdditionsData.h. DO NOT EDIT.\n\n");
    std::printf("package paint\n\n");
    std::printf("// TrackAdditionSupport is Style1::TrackAdditionSupport (a track extra's support).\n");
    std::printf("type TrackAdditionSupport struct {\n\tImageIDs [4][2]uint32\n\tHeight int16\n\tFrequencies [4]uint8\n\tSegments [4]uint16\n}\n\n");
    std::printf("// TrackAdditionPiece is TrackPaintAdditionPiece (Style0 and Style1; Supports Style1 only).\n");
    std::printf("type TrackAdditionPiece struct {\n\tImageIDs [4]uint32\n\tBBOffsets, BBSizes [4]Pos3\n\tIsMergeable bool\n\tSupports *TrackAdditionSupport\n}\n\n");
    std::printf("// TrackAdditionParts0 / 1 are Style0 / Style1 kTrackPaintAdditionParts [trackId][sequenceIndex].\n");
    table("TrackAdditionParts0", Style0::kTrackPaintAdditionParts);
    table("TrackAdditionParts1", Style1::kTrackPaintAdditionParts);
}

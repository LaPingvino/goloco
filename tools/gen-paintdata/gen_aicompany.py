#!/usr/bin/env python3
"""Writes pkg/sim/aicompany_gen.go from upstream's own tables: createCompany's
kAiPrimaryColours, kCompanyAiPlaystyleFlags, kCompanyAiNamePrefixes and
kCompanyAiPlaystyleString (World/CompanyManager.cpp), the colour names
resolved by Graphics/Colour.h, the playstyle flags by World/Company.h, the
string ids named as pkg/i18n's constants (snake_case to CamelCase).
Usage: gen_aicompany.py [OpenLoco dir]"""
import os, re, subprocess, sys

ol = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser("~/Projects/OpenLoco")
repo = os.path.abspath(os.path.join(os.path.dirname(__file__), "../.."))
inc = os.path.join(ol, "src/OpenLoco/include/OpenLoco")
src = open(os.path.join(ol, "src/OpenLoco/src/World/CompanyManager.cpp")).read()


def table(name):
    m = re.search(r"%s = \{(.*?)\};" % name, src, re.S)
    return [e.strip() for e in re.sub(r"//[^\n]*", "", m.group(1)).split(",") if e.strip()]


def enum(path, name):
    body = re.search(r"enum class %s\s*:\s*\w+\s*\{(.*?)\};" % name, open(path).read(), re.S).group(1)
    vals, nxt = {}, 0
    for line in re.sub(r"//[^\n]*", "", body).split(","):
        line = line.strip()
        if not line:
            continue
        if "=" in line:
            k, v = [s.strip() for s in line.split("=", 1)]
            nxt = eval(v.replace("U", ""))
        else:
            k = line
        vals[k] = nxt
        nxt += 1
    return vals


colours = enum(os.path.join(inc, "Graphics/Colour.h"), "Colour")
flags = enum(os.path.join(inc, "World/Company.h"), "AiPlaystyleFlags")


def camel(s):
    return "".join(p[:1].upper() + p[1:] for p in s.split("_"))


out = ["// Code generated by tools/gen-paintdata/gen_aicompany.py from World/CompanyManager.cpp; DO NOT EDIT.", "",
       "package sim", "", 'import "github.com/LaPingvino/goloco/pkg/i18n"', ""]
c = table("kAiPrimaryColours")
out.append("// aiPrimaryColours is kAiPrimaryColours (0x004F93F8): a name prefix's colour, colourMax for a random one.")
out.append("var aiPrimaryColours = [%d]uint8{%s}" % (len(c), ", ".join(str(colours[e.split("::")[1]]) for e in c)))
f = table("kCompanyAiPlaystyleFlags")
vals = []
for e in f:
    v = 0
    for part in e.split("|"):
        v |= flags[part.strip().split("::")[1]]
    vals.append("%#x" % v)
out.append("")
out.append("// companyAiPlaystyleFlags is kCompanyAiPlaystyleFlags (0x004F93C4): AiPlaystyleFlags by playstyle.")
out.append("var companyAiPlaystyleFlags = [%d]uint32{%s}" % (len(vals), ", ".join(vals)))
for go, cpp, doc in (("companyAiNamePrefixes", "kCompanyAiNamePrefixes", "the name prefix strings"),
                     ("companyAiPlaystyleString", "kCompanyAiPlaystyleString", "the company name string by playstyle")):
    t = table(cpp)
    out.append("")
    out.append("// %s is %s: %s." % (go, cpp, doc))
    out.append("var %s = [%d]int{%s}" % (go, len(t), ", ".join("i18n." + camel(e.split("::")[1]) for e in t)))
path = os.path.join(repo, "pkg/sim/aicompany_gen.go")
open(path, "w").write("\n".join(out) + "\n")
subprocess.run(["gofmt", "-w", path], check=True)

// gen_roadnextto.cpp — prints TrackData::getRoadUnkNextTo (the building
// positions beside a road piece Town::constructBuilding picks from) as Go,
// indexed by roadAndDirection / 4 (20 entries, the size of kRoadUnkNextTo).
#include "Map/Track/TrackData.h"
#include <cstdio>

using namespace OpenLoco::World::TrackData;

int main()
{
    std::printf("// Code generated by tools/gen-paintdata from OpenLoco src/Map/Track/TrackData.cpp. DO NOT EDIT.\n\n");
    std::printf("package sim\n\n");
    std::printf("// RoadUnkNextTo is TrackData::RoadUnkNextTo: an offset (world units) and rotation.\n");
    std::printf("type RoadUnkNextTo struct {\n\tX, Y, Z  int16\n\tRotation uint8\n}\n\n");
    std::printf("// RoadNextTo is getRoadUnkNextTo, by roadAndDirection / 4.\n");
    std::printf("var RoadNextTo = [20][]RoadUnkNextTo{\n");
    for (int i = 0; i < 20; i++)
    {
        std::printf("\t{");
        for (const auto& n : getRoadUnkNextTo(i * 4))
        {
            std::printf("{%d, %d, %d, %u}, ", n.pos.x, n.pos.y, n.pos.z, n.rotation);
        }
        std::printf("},\n");
    }
    std::printf("}\n");
}

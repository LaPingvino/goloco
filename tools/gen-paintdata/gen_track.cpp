// gen_track.cpp — dumps OpenLoco's track paint table (PaintTrackData.h) as Go
// source. Separate from gen.cpp because upstream compiles the track and road
// data in separate translation units (they define the same helper constants).
#include "Paint/PaintTrack.h"
#include "Graphics/ImageIds.h"
#include "Map/TrackElement.h"
#include "Objects/TrackObject.h"
#include "Paint/Paint.h"
#include "Paint/PaintTrackData.h"
#include "Map/Track/TrackData.h"
#include <cstdio>
#include <type_traits>

using namespace OpenLoco;
using namespace OpenLoco::Paint;


static void pos(const World::Pos3& p) { std::printf("{%d, %d, %d}", p.x, p.y, p.z); }

template<typename T, size_t N>
static void arr(const std::array<T, N>& a)
{
    std::printf("{");
    for (size_t i = 0; i < N; i++)
    {
        if (i)
            std::printf(", ");
        if constexpr (std::is_enum_v<T>)
            std::printf("%u", static_cast<unsigned>(static_cast<std::underlying_type_t<T>>(a[i])));
        else if constexpr (std::is_signed_v<T>)
            std::printf("%d", static_cast<int>(a[i]));
        else
            std::printf("%u", static_cast<unsigned>(a[i]));
    }
    std::printf("}");
}

template<typename T, size_t N, size_t M>
static void arr2(const std::array<std::array<T, M>, N>& a)
{
    std::printf("{");
    for (size_t i = 0; i < N; i++)
    {
        if (i)
            std::printf(", ");
        arr(a[i]);
    }
    std::printf("}");
}

static void trackPiece(const TrackPaintPiece& p)
{
    std::printf("\t\t{ImageIndexOffsets: [4][3]uint32"); arr2(p.imageIndexOffsets);
    std::printf(", BBOffsets: [4]Pos3{");
    for (int i = 0; i < 4; i++) { if (i) std::printf(", "); pos(p.boundingBoxOffsets[i]); }
    std::printf("}, BBSizes: [4]Pos3{");
    for (int i = 0; i < 4; i++) { if (i) std::printf(", "); pos(p.boundingBoxSizes[i]); }
    std::printf("},\n\t\t\tBridgeEdges: [4]uint8"); arr(p.bridgeEdges);
    std::printf(", BridgeQuarters: [4]uint8"); arr(p.bridgeQuarters);
    std::printf(", BridgeType: [4]uint8"); arr(p.bridgeType);
    std::printf(", TunnelHeights: [4][4]int16"); arr2(p.tunnelHeights);
    std::printf(", Segments: [4]uint16"); arr(p.segments);
    std::printf(", IsMergeable: %s},\n", p.isMergeable ? "true" : "false");
}


template<typename P, size_t N, typename F>
static void table(const char* name, const char* type, const std::array<std::span<const P>, N>& t, F each)
{
    std::printf("var %s = [%zu][]%s{\n", name, N, type);
    for (size_t r = 0; r < N; r++)
    {
        std::printf("\t// trackId %zu\n\t{\n", r);
        for (const auto& p : t[r])
            each(p);
        std::printf("\t},\n");
    }
    std::printf("}\n\n");
}

int main()
{
    std::printf("// Code generated by tools/gen-paintdata from OpenLoco include/OpenLoco/Paint/PaintTrackData.h. DO NOT EDIT.\n\n");
    std::printf("package paint\n\n");
    std::printf("// TrackPiece is TrackPaintPiece (PaintTrackData.h).\n");
    std::printf("type TrackPiece struct {\n\tImageIndexOffsets [4][3]uint32\n\tBBOffsets, BBSizes [4]Pos3\n\tBridgeEdges, BridgeQuarters, BridgeType [4]uint8\n\tTunnelHeights [4][4]int16\n\tSegments [4]uint16\n\tIsMergeable bool\n}\n\n");
    table("TrackParts", "TrackPiece", kTrackPaintParts, trackPiece);
    // World::TrackData::getTrackMiscData(trackId).signalHeightOffsetLeft/Right
    std::printf("// TrackSignalHeightOffset[trackId] = {left, right} (TrackData getTrackMiscData).\n");
    std::printf("var TrackSignalHeightOffset = [%zu][2]uint8{\n", kTrackPaintParts.size());
    for (size_t i = 0; i < kTrackPaintParts.size(); i++)
    {
        const auto& m = World::TrackData::getTrackMiscData(i);
        std::printf("\t{%u, %u},\n", (unsigned)m.signalHeightOffsetLeft, (unsigned)m.signalHeightOffsetRight);
    }
    std::printf("}\n");
}

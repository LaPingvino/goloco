using namespace OpenLoco;
using namespace OpenLoco::Paint;

static void pos(const World::Pos3& p) { std::printf("{%d, %d, %d}", p.x, p.y, p.z); }

template<typename T, size_t N>
static void arr(const std::array<T, N>& a)
{
    std::printf("{");
    for (size_t i = 0; i < N; i++)
    {
        if (i)
            std::printf(", ");
        if constexpr (std::is_enum_v<T>)
            std::printf("%u", static_cast<unsigned>(static_cast<std::underlying_type_t<T>>(a[i])));
        else if constexpr (std::is_signed_v<T>)
            std::printf("%d", static_cast<int>(a[i]));
        else
            std::printf("%u", static_cast<unsigned>(a[i]));
    }
    std::printf("}");
}

template<typename T, size_t N, size_t M>
static void arr2(const std::array<std::array<T, M>, N>& a)
{
    std::printf("{");
    for (size_t i = 0; i < N; i++)
    {
        if (i)
            std::printf(", ");
        arr(a[i]);
    }
    std::printf("}");
}

static void common(const RoadPaintCommonPiece& p)
{
    std::printf("\t\t{BBOffsets: [4]Pos3{");
    for (int i = 0; i < 4; i++) { if (i) std::printf(", "); pos(p.boundingBoxOffsets[i]); }
    std::printf("}, BBSizes: [4]Pos3{");
    for (int i = 0; i < 4; i++) { if (i) std::printf(", "); pos(p.boundingBoxSizes[i]); }
    std::printf("},\n\t\t\tBridgeEdges: [4]uint8"); arr(p.bridgeEdges);
    std::printf(", BridgeQuarters: [4]uint8"); arr(p.bridgeQuarters);
    std::printf(", BridgeType: [4]uint8"); arr(p.bridgeType);
    std::printf(",\n\t\t\tTunnelHeights: [4][4]int16"); arr2(p.tunnelHeights);
    std::printf(", Segments: [4]uint16"); arr(p.segments);
    std::printf("},\n");
}

static void mergeable(const RoadPaintMergeablePiece& p)
{
    std::printf("\t\t{ImageIndexOffsets: [4]uint32"); arr(p.imageIndexOffsets);
    std::printf(", StreetlightHeights: [4][4]int16"); arr2(p.streetlightHeights);
    std::printf(", MergeType: [4]uint8"); arr(p.isMultiTileMerge);
    std::printf("},\n");
}

static void style1(const Style1::RoadPaintPiece& p)
{
    std::printf("\t\t{ImageIndexOffsets: [4][3]uint32"); arr2(p.imageIndexOffsets);
    std::printf("},\n");
}

template<typename P, size_t N, typename F>
static void table(const char* name, const char* type, const std::array<std::span<const P>, N>& t, F each)
{
    std::printf("var %s = [%zu][]%s{\n", name, N, type);
    for (size_t r = 0; r < N; r++)
    {
        std::printf("\t// roadId %zu\n\t{\n", r);
        for (const auto& p : t[r])
            each(p);
        std::printf("\t},\n");
    }
    std::printf("}\n\n");
}

int main()
{
    std::printf("// Code generated by tools/gen-paintdata from OpenLoco include/OpenLoco/Paint/\n");
    std::printf("// PaintRoadCommonData.h, PaintRoadStyle{0,1,2}Data.h, RoadObject.h and WallObject.h. DO NOT EDIT.\n\n");
    std::printf("package paint\n\n");
    std::printf("// RoadCommonPiece is RoadPaintCommonPiece (per rotation).\n");
    std::printf("type RoadCommonPiece struct {\n\tBBOffsets, BBSizes [4]Pos3\n\tBridgeEdges, BridgeQuarters, BridgeType [4]uint8\n\tTunnelHeights [4][4]int16\n\tSegments [4]uint16\n}\n\n");
    std::printf("// RoadMergeablePiece is RoadPaintMergeablePiece (styles 0 and 2).\n");
    std::printf("type RoadMergeablePiece struct {\n\tImageIndexOffsets [4]uint32\n\tStreetlightHeights [4][4]int16\n\tMergeType [4]uint8 // RoadPaintMergeType: 0 none, 1 standard, 2 left, 3 right\n}\n\n");
    std::printf("// RoadStyle1Piece is Style1::RoadPaintPiece.\n");
    std::printf("type RoadStyle1Piece struct {\n\tImageIndexOffsets [4][3]uint32\n}\n\n");
    // PaintRoad.cpp Style02::kMergeBaseImageIndex (indexed by RoadPaintMergeType - 1)
    std::printf("// RoadMergeBaseImage is Style02::kMergeBaseImageIndex (PaintRoad.cpp), offsets from the road\n");
    std::printf("// object's image, indexed by MergeType-1.\n");
    std::printf("var RoadMergeBaseImage = [3]uint32{%u, %u, %u}\n\n",
        (unsigned)RoadObj::ImageIds::Style0::kStraight0NE, (unsigned)RoadObj::ImageIds::Style2::kStraight0NE, (unsigned)RoadObj::ImageIds::Style2::kStraight0SW);
    {
        using namespace OpenLoco::WallObj::ImageIds;
        std::printf("// Wall image offsets (WallObject.h WallObj::ImageIds), from the wall object's sprite.\n");
        std::printf("const (\n\tWallSlopedNE = %u\n\tWallSlopedSE = %u\n\tWallSlopedSW = %u\n\tWallSlopedNW = %u\n\tWallFlatNE = %u\n\tWallFlatSE = %u\n",
            (unsigned)kSlopedNE, (unsigned)kSlopedSE, (unsigned)kSlopedSW, (unsigned)kSlopedNW, (unsigned)kFlatNE, (unsigned)kFlatSE);
        std::printf("\tWallGlassSlopedNE = %u\n\tWallGlassSlopedSE = %u\n\tWallGlassSlopedSW = %u\n\tWallGlassSlopedNW = %u\n\tWallGlassFlatNE = %u\n\tWallGlassFlatSE = %u\n)\n\n",
            (unsigned)kGlassSlopedNE, (unsigned)kGlassSlopedSE, (unsigned)kGlassSlopedSW, (unsigned)kGlassSlopedNW, (unsigned)kGlassFlatNE, (unsigned)kGlassFlatSE);
    }
    table("RoadCommonParts", "RoadCommonPiece", kRoadPaintCommonParts, common);
    table("RoadStyle0Parts", "RoadMergeablePiece", Style0::kRoadPaintParts, mergeable);
    table("RoadStyle1Parts", "RoadStyle1Piece", Style1::kRoadPaintParts, style1);
    table("RoadStyle2Parts", "RoadMergeablePiece", Style2::kRoadPaintParts, mergeable);
}

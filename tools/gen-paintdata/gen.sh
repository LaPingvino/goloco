#!/usr/bin/env bash
# gen.sh — regenerate pkg/paint/roaddata_gen.go from an OpenLoco checkout.
#   tools/gen-paintdata/gen.sh [~/Projects/OpenLoco]
set -euo pipefail
OL=${1:-$HOME/Projects/OpenLoco}
here=$(cd "$(dirname "$0")" && pwd)
repo=$(cd "$here/../.." && pwd)
inc=(-I"$OL/src/OpenLoco/include" -I"$OL/src/OpenLoco/src" -I"$OL/src/OpenLoco/include/OpenLoco" -I"$OL/src/Audio/include"
     -I"$OL/src/Core/include" -I"$OL/build/_deps/fmt-src/include" -I"$OL/build/_deps/sfl-src/include" -I"$OL/src/Diagnostics/include"
     -I"$OL/src/Platform/include" -I"$OL/src/Utility/include" -I"$OL/src/Math/include" -I"$OL/src/Engine/include" -I"$OL/src/Gfx/include")
tmp=$(mktemp -d)
g++ -std=c++20 -fno-char8_t -DDEBUG=0 "${inc[@]}" -o "$tmp/gen" "$here/gen.cpp"
g++ -std=c++20 -fno-char8_t -DDEBUG=0 "${inc[@]}" -o "$tmp/gen_track" "$here/gen_track.cpp" "$OL/src/OpenLoco/src/Map/Track/TrackData.cpp"
"$tmp/gen" > "$repo/pkg/paint/roaddata_gen.go"
"$tmp/gen_track" > "$repo/pkg/paint/trackdata_gen.go"
g++ -std=c++20 -fno-char8_t -DDEBUG=0 "${inc[@]}" -o "$tmp/gen_trackaddition" "$here/gen_trackaddition.cpp"
"$tmp/gen_trackaddition" > "$repo/pkg/paint/trackadditiondata_gen.go"
gofmt -w "$repo/pkg/paint/trackadditiondata_gen.go"
g++ -std=c++20 -fno-char8_t -DDEBUG=0 "${inc[@]}" -o "$tmp/gen_roadaddition" "$here/gen_roadaddition.cpp"
"$tmp/gen_roadaddition" > "$repo/pkg/paint/roadadditiondata_gen.go"
gofmt -w "$repo/pkg/paint/roadadditiondata_gen.go"
g++ -std=c++20 -fno-char8_t -DDEBUG=0 "${inc[@]}" -I"$OL/src/OpenLoco/src" -o "$tmp/gen_subposition" "$here/gen_subposition.cpp"
"$tmp/gen_subposition" > "$repo/pkg/sim/subposition_gen.go"
gofmt -w "$repo/pkg/sim/subposition_gen.go"
gofmt -w "$repo/pkg/paint/roaddata_gen.go" "$repo/pkg/paint/trackdata_gen.go"
echo "wrote pkg/paint/roaddata_gen.go + trackdata_gen.go (OpenLoco $(git -C "$OL" rev-parse --short HEAD 2>/dev/null || echo '?'))"

# Plain integer tables that live inside upstream .cpp files (static, not in a
# header): extracted from the source literally, no hand copying.
{
  echo "// Code generated by tools/gen-paintdata/gen.sh from OpenLoco src/Paint/PaintSurface.cpp. DO NOT EDIT."
  echo
  echo "package paint"
  echo
  echo "// SurfaceTreeHeight is PaintSurface.cpp k4FD30C: height offset of an industry field's"
  echo "// tree image per display slope."
  printf "var SurfaceTreeHeight = [19]int16{"
  awk '/k4FD30C = \{/,/\};/' "$OL/src/OpenLoco/src/Paint/PaintSurface.cpp" | tr -d ' \n' | sed 's/.*{//; s/,*};.*//'
  echo "}"
} > "$repo/pkg/paint/surfacedata_gen.go"
gofmt -w "$repo/pkg/paint/surfacedata_gen.go"

# Tables of ImageIds names inside upstream .cpp files: take the names in order
# from the source, let the compiler resolve their values.
snowNames=$(awk '/kSnowCoverageSlopeToMask = \{/,/^    \};/' "$OL/src/OpenLoco/src/Paint/PaintSurface.cpp" | grep -o 'ImageIds::[A-Za-z0-9_]*')
{
  echo '#include "Graphics/ImageIds.h"'
  echo '#include "Objects/SnowObject.h"'
  echo '#include <cstdio>'
  echo 'using namespace OpenLoco;'
  echo 'int main() {'
  echo '  std::printf("// SnowCoverageSlopeToMask is PaintSurface.cpp kSnowCoverageSlopeToMask [coverage-1][displaySlope].\n");'
  echo '  std::printf("var SnowCoverageSlopeToMask = [4][19]uint32{\n");'
  i=0
  for n in $snowNames; do
    if [ $((i % 19)) -eq 0 ]; then echo '  std::printf("\t{");'; fi
    echo "  std::printf(\"%u, \", (unsigned)$n);"
    if [ $((i % 19)) -eq 18 ]; then echo '  std::printf("},\n");'; fi
    i=$((i+1))
  done
  echo '  std::printf("}\n\n");'
  echo '  std::printf("// SnowObjectSize is sizeof(SnowObject); SnowSurfaceFullZoom is SnowLine::ImageIds::surfaceFullZoom.\n");'
  echo '  std::printf("const (\n\tSnowObjectSize = %zu\n\tSnowSurfaceFullZoom = %u\n)\n", sizeof(SnowObject), (unsigned)SnowLine::ImageIds::surfaceFullZoom);'
  echo '}'
} > "$tmp/snow.cpp"
g++ -std=c++20 -fno-char8_t -DDEBUG=0 "${inc[@]}" -o "$tmp/snow" "$tmp/snow.cpp"
"$tmp/snow" >> "$repo/pkg/paint/surfacedata_gen.go"
gofmt -w "$repo/pkg/paint/surfacedata_gen.go"
# Landscape smoothing tables (paintSurfaceSmoothenEdge): the definitions are
# copied out of PaintSurface.cpp verbatim and printed by the compiler.
{
  echo '#include "Graphics/ImageIds.h"'
  echo '#include <array>'
  echo '#include <cstdint>'
  echo '#include <cstdio>'
  echo 'using namespace OpenLoco;'
  for t in k4FDA5E k4FDA71 k4FDA84 k4FDA97 kSurfaceSmoothFromSlope; do
    awk "/$t = \\{/,/^    \\};/" "$OL/src/OpenLoco/src/Paint/PaintSurface.cpp"
  done
  echo 'int main() {'
  for t in k4FDA5E k4FDA71 k4FDA84 k4FDA97; do
    echo "  std::printf(\"// Surface$t is PaintSurface.cpp $t (paintSurfaceSmoothenEdge), by display slope.\\nvar Surface$t = [19]uint8{\");"
    echo "  for (auto v : $t) std::printf(\"%u, \", (unsigned)v);"
    echo '  std::printf("}\n\n");'
  done
  echo '  std::printf("// SurfaceSmoothFromSlope is PaintSurface.cpp kSurfaceSmoothFromSlope [edge][displaySlope].\nvar SurfaceSmoothFromSlope = [4][19]uint32{\n");'
  echo '  for (auto& e : kSurfaceSmoothFromSlope) { std::printf("\t{"); for (auto v : e) std::printf("%u, ", (unsigned)v); std::printf("},\n"); }'
  echo '  std::printf("}\n");'
  echo '}'
} > "$tmp/smooth.cpp"
g++ -std=c++20 -fno-char8_t -DDEBUG=0 "${inc[@]}" -o "$tmp/smooth" "$tmp/smooth.cpp"
"$tmp/smooth" >> "$repo/pkg/paint/surfacedata_gen.go"
gofmt -w "$repo/pkg/paint/surfacedata_gen.go"
# Object struct layouts for pkg/objects (sizes and field offsets the loaders
# read), straight from the compiler.
cat > "$tmp/layout.cpp" <<'CPP'
#include "Objects/AirportObject.h"
#include "Objects/BuildingObject.h"
#include "Objects/DockObject.h"
#include "Objects/BridgeObject.h"
#include "Objects/TunnelObject.h"
#include "Objects/RoadStationObject.h"
#include "Objects/TrainStationObject.h"
#include <cstddef>
#include <cstdio>
using namespace OpenLoco;
int main() {
  std::printf("// Code generated by tools/gen-paintdata/gen.sh from OpenLoco headers. DO NOT EDIT.\n\npackage objects\n\n");
  std::printf("// AirportObject layout (Objects/AirportObject.h).\nconst (\n");
  std::printf("\tAirportObjectSize = %zu\n", sizeof(AirportObject));
  std::printf("\tAirportFlagsOffset = %zu\n", offsetof(AirportObject, flags));
  std::printf("\tAirportNumSpriteSetsOffset = %zu\n", offsetof(AirportObject, numSpriteSets));
  std::printf("\tAirportNumTilesOffset = %zu\n", offsetof(AirportObject, numTiles));
  std::printf("\tAirportLargeTilesOffset = %zu\n", offsetof(AirportObject, largeTiles));
  std::printf("\tAirportNumMovementNodesOffset = %zu\n", offsetof(AirportObject, numMovementNodes));
  std::printf("\tAirportNumMovementEdgesOffset = %zu\n", offsetof(AirportObject, numMovementEdges));
  std::printf("\tAirportBuildingSize = %zu\n", sizeof(AirportBuilding));
  std::printf("\tAirportMovementNodeSize = %zu\n", sizeof(AirportObject::MovementNode));
  std::printf("\tAirportMovementEdgeSize = %zu\n", sizeof(AirportObject::MovementEdge));
  std::printf("\tAirportFlagHasShadows = %u\n", (unsigned)AirportObjectFlags::hasShadows);
  std::printf("\tBuildingPartAnimationSize = %zu\n", sizeof(BuildingPartAnimation));
  std::printf("\tDockObjectSize = %zu\n", sizeof(DockObject));
  std::printf("\tDockFlagsOffset = %zu\n", offsetof(DockObject, flags));
  std::printf("\tDockNumBuildingPartsOffset = %zu\n", offsetof(DockObject, numBuildingParts));
  std::printf("\tDockNumBuildingVariationsOffset = %zu\n", offsetof(DockObject, numBuildingVariations));
  std::printf("\tDockFlagHasShadows = %u\n", (unsigned)DockObjectFlags::hasShadows);
  std::printf("\tTunnelObjectSize = %zu\n", sizeof(TunnelObject));
  std::printf("\tBridgeObjectSize = %zu\n", sizeof(BridgeObject));
  std::printf("\tBridgeFlagsOffset = %zu\n", offsetof(BridgeObject, flags));
  std::printf("\tBridgeClearHeightOffset = %zu\n", offsetof(BridgeObject, clearHeight));
  std::printf("\tBridgeDeckDepthOffset = %zu\n", offsetof(BridgeObject, deckDepth));
  std::printf("\tBridgeSpanLengthOffset = %zu\n", offsetof(BridgeObject, spanLength));
  std::printf("\tBridgePillarSpacingOffset = %zu\n", offsetof(BridgeObject, pillarSpacing));
  std::printf("\tBridgeMaxSpeedOffset = %zu\n", offsetof(BridgeObject, maxSpeed));
  std::printf("\tBridgeMaxHeightOffset = %zu\n", offsetof(BridgeObject, maxHeight));
  std::printf("\tBridgeTrackNumCompatibleOffset = %zu\n", offsetof(BridgeObject, trackNumCompatible));
  std::printf("\tBridgeRoadNumCompatibleOffset = %zu\n", offsetof(BridgeObject, roadNumCompatible));
  std::printf("\tBridgeDesignedYearOffset = %zu\n", offsetof(BridgeObject, designedYear));
  std::printf("\tBridgeFlagHasRoof = %u\n", (unsigned)BridgeObjectFlags::hasRoof);
  std::printf("\tTrainStationFlagsOffset = %zu\n", offsetof(TrainStationObject, flags));
  std::printf("\tTrainStationFlagRecolourable = %u\n", (unsigned)TrainStationFlags::recolourable);
  std::printf("\tRoadStationFlagsOffset = %zu\n", offsetof(RoadStationObject, flags));
  std::printf("\tRoadStationFlagRecolourable = %u\n", (unsigned)RoadStationFlags::recolourable);
  std::printf(")\n");
}
CPP
g++ -std=c++20 -fno-char8_t -DDEBUG=0 "${inc[@]}" -o "$tmp/layout" "$tmp/layout.cpp"
"$tmp/layout" > "$repo/pkg/objects/layout_gen.go"
gofmt -w "$repo/pkg/objects/layout_gen.go"
# Colour tables (Graphics/PaletteMap.cpp kDefaultPaletteToG1Offset, Colour.cpp
# _translucentColourMap / _shadowColourMap): names in order from the source,
# values from the compiler.
pal=$(awk '/kDefaultPaletteToG1Offset = \{/,/^    \};/' "$OL/src/OpenLoco/src/Graphics/PaletteMap.cpp" | grep -o 'ImageIds::[A-Za-z0-9_]*')
tr=$(awk '/_translucentColourMap = \{/,/^    \};/' "$OL/src/OpenLoco/src/Graphics/Colour.cpp" | grep -o 'ExtColour::[A-Za-z0-9_]*')
sh=$(awk '/_shadowColourMap = \{/,/^    \};/' "$OL/src/OpenLoco/src/Graphics/Colour.cpp" | grep -o 'ExtColour::[A-Za-z0-9_]*')
{
  echo '#include "Graphics/Colour.h"'
  echo '#include "Graphics/ImageIds.h"'
  echo '#include <cstdio>'
  echo 'using namespace OpenLoco;'
  echo 'int main(int argc, char**) {'
  echo '  if (argc > 1) {'
  echo '  std::printf("// Code generated by tools/gen-paintdata/gen.sh from OpenLoco Graphics/PaletteMap.cpp. DO NOT EDIT.\n\npackage assets\n\n");'
  echo '  std::printf("// PaletteToG1 is kDefaultPaletteToG1Offset: ExtColour → g1 image of its palette map.\nvar PaletteToG1 = [...]uint32{");'
  for n in $pal; do echo "  std::printf(\"%u, \", (unsigned)$n);"; done
  echo '  std::printf("}\n"); return 0; }'
  echo '  std::printf("// Code generated by tools/gen-paintdata/gen.sh from OpenLoco Graphics/Colour.cpp. DO NOT EDIT.\n\npackage paint\n\n");'
  echo '  std::printf("// TranslucentColour is _translucentColourMap [colour][shade] (ExtColour).\nvar TranslucentColour = [31][3]uint8{");'
  i=0; for n in $tr; do
    [ $((i % 3)) -eq 0 ] && echo '  std::printf("{");'
    echo "  std::printf(\"%u, \", (unsigned)$n);"
    [ $((i % 3)) -eq 2 ] && echo '  std::printf("}, ");'
    i=$((i+1)); done
  echo '  std::printf("}\n\n// ShadowColour is _shadowColourMap [colour] (ExtColour).\nvar ShadowColour = [31]uint8{");'
  for n in $sh; do echo "  std::printf(\"%u, \", (unsigned)$n);"; done
  echo '  std::printf("}\n\n// ExtColourUnk2E is ExtColour::unk2E (translucentGlass1): the canopy of non-recolourable stations.\nconst ExtColourUnk2E = %u\n", (unsigned)ExtColour::unk2E);'
  echo '}'
} > "$tmp/colours.cpp"
g++ -std=c++20 -fno-char8_t -DDEBUG=0 "${inc[@]}" -o "$tmp/colours" "$tmp/colours.cpp"
"$tmp/colours" > "$repo/pkg/paint/colourdata_gen.go"
"$tmp/colours" pal > "$repo/pkg/assets/palettedata_gen.go"
gofmt -w "$repo/pkg/paint/colourdata_gen.go" "$repo/pkg/assets/palettedata_gen.go"
# PaintBridge.cpp's tables: the .cpp itself is included (gen_bridge.cpp).
g++ -std=c++20 -fno-char8_t -DDEBUG=0 "${inc[@]}" -O1 -ffunction-sections -fdata-sections -Wl,--gc-sections -o "$tmp/gen_bridge" "$here/gen_bridge.cpp"
"$tmp/gen_bridge" > "$repo/pkg/paint/bridgedata_gen.go"
gofmt -w "$repo/pkg/paint/bridgedata_gen.go"
# Every Bridge::ImageIds name PaintBridge.cpp uses, as Go constants (values from the compiler).
bnames=$(grep -o 'Bridge::ImageIds::[A-Za-z0-9_]*' "$OL/src/OpenLoco/src/Paint/PaintBridge.cpp" | sort -u | sed 's/Bridge::ImageIds:://')
{
  echo '#include "Objects/BridgeObject.h"'
  echo '#include <cstdio>'
  echo 'using namespace OpenLoco;'
  echo 'int main() {'
  echo '  std::printf("// Code generated by tools/gen-paintdata/gen.sh from OpenLoco Objects/BridgeObject.h (names used by PaintBridge.cpp). DO NOT EDIT.\n\npackage paint\n\n// Bridge::ImageIds offsets into the bridge object image table.\nconst (\n");'
  for n in $bnames; do
    go="BridgeImg$(echo "${n:0:1}" | tr a-z A-Z)${n:1}"
    echo "  std::printf(\"\t$go = %u\n\", (unsigned)Bridge::ImageIds::$n);"
  done
  echo '  std::printf(")\n");'
  echo '}'
} > "$tmp/bridgeids.cpp"
g++ -std=c++20 -fno-char8_t -DDEBUG=0 "${inc[@]}" -o "$tmp/bridgeids" "$tmp/bridgeids.cpp"
"$tmp/bridgeids" > "$repo/pkg/paint/bridgeids_gen.go"
gofmt -w "$repo/pkg/paint/bridgeids_gen.go"
g++ -std=c++20 -fno-char8_t -DDEBUG=0 "${inc[@]}" -O1 -ffunction-sections -fdata-sections -Wl,--gc-sections -o "$tmp/gen_surface" "$here/gen_surface.cpp"
"$tmp/gen_surface" > "$repo/pkg/paint/surfacesupport_gen.go"
gofmt -w "$repo/pkg/paint/surfacesupport_gen.go"
# PaletteIndex::primaryRemap0..B (getShade reads a colour's palette map at these).
cat > "$tmp/pi.cpp" <<'CPP'
#include "Graphics/Colour.h"
#include <cstdio>
int main() {
  using namespace OpenLoco::PaletteIndex;
  unsigned v[] = {primaryRemap0, primaryRemap1, primaryRemap2, primaryRemap3, primaryRemap4, primaryRemap5,
                  primaryRemap6, primaryRemap7, primaryRemap8, primaryRemap9, primaryRemapA, primaryRemapB};
  std::printf("// Code generated by tools/gen-paintdata/gen.sh from OpenLoco Graphics/Colour.h. DO NOT EDIT.\n\npackage gfx8\n\n");
  std::printf("// PrimaryRemap is PaletteIndex::primaryRemap0..B.\nvar PrimaryRemap = [12]uint8{");
  for (auto x : v) std::printf("%u, ", x);
  std::printf("}\n");
}
CPP
g++ -std=c++20 -fno-char8_t -DDEBUG=0 "${inc[@]}" -o "$tmp/pi" "$tmp/pi.cpp"
"$tmp/pi" > "$repo/pkg/gfx8/paletteindex_gen.go"
gofmt -w "$repo/pkg/gfx8/paletteindex_gen.go"
# Dropdown.cpp kDropdownColourTable (names in order from the source, values from the compiler).
ddn=$(awk '/kDropdownColourTable = \{/,/^    \} \};/' "$OL/src/OpenLoco/src/Ui/Dropdown.cpp" | grep -o 'Colour::[A-Za-z0-9_]*')
{
  echo '#include "Graphics/Colour.h"'
  echo '#include <cstdio>'
  echo 'using namespace OpenLoco;'
  echo 'int main() {'
  echo '  std::printf("// Code generated by tools/gen-paintdata/gen.sh from OpenLoco src/Ui/Dropdown.cpp. DO NOT EDIT.\n\npackage ui\n\n// DropdownColourTable is kDropdownColourTable: a translucent window colour → the dropdown colour.\nvar DropdownColourTable = [...]uint8{");'
  for n in $ddn; do echo "  std::printf(\"%u, \", (unsigned)$n);"; done
  echo '  std::printf("}\n");'
  echo '}'
} > "$tmp/ddc.cpp"
g++ -std=c++20 -fno-char8_t -DDEBUG=0 "${inc[@]}" -o "$tmp/ddc" "$tmp/ddc.cpp"
"$tmp/ddc" > "$repo/pkg/ui/dropdowncolour_gen.go"
gofmt -w "$repo/pkg/ui/dropdowncolour_gen.go"
rm -rf "$tmp"

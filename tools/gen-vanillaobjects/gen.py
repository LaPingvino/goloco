#!/usr/bin/env python
"""Generates pkg/objects/vanilla_gen.go from OpenLoco's Objects/Object.cpp
(_vanillaObjects: the original game's objects by name and type, which
ObjectHeader::isVanilla looks up).

    python tools/gen-vanillaobjects/gen.py ~/Projects/OpenLoco | gofmt > pkg/objects/vanilla_gen.go
"""
import os, re, sys

up = sys.argv[1]
cpp = open(os.path.join(up, "src/OpenLoco/src/Objects/Object.cpp")).read()
body = re.search(r"_vanillaObjects = \{(.*?)\n    \};", cpp, re.S).group(1)
entries = re.findall(r'\{ "([^"]{8})", ObjectType::(\w+) \}', body)
assert len(entries) == body.count("ObjectType::"), "unparsed entries"
hdr = open(os.path.join(up, "src/OpenLoco/include/OpenLoco/Objects/Object.h")).read()
enum = re.search(r"enum class ObjectType : uint8_t\s*\{(.*?)\};", hdr, re.S).group(1)
types = [re.sub(r"//.*", "", n).split("=")[0].strip() for n in enum.split(",")]
types = [t for t in types if t]
idx = {t: i for i, t in enumerate(types)}

print("// Code generated by tools/gen-vanillaobjects/gen.py from OpenLoco src/Objects/Object.cpp. DO NOT EDIT.")
print()
print("package objects")
print()
print("// vanillaObjects is _vanillaObjects: the original game's objects, unique by")
print("// name and type (ObjectHeader::isVanilla).")
print("var vanillaObjects = map[vanillaKey]struct{}{")
for name, t in entries:
    print('\t{"%s", %d}: {}, // %s' % (name, idx[t], t))
print("}")

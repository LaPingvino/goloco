// Command genstringids writes pkg/i18n/stringids.go from OpenLoco's
// Localisation/StringIds.h: every StringIds constant, its upstream name in
// Go case (options_language → OptionsLanguage), the same number.
//
//	go run ./cmd/genstringids -openloco ../OpenLoco
package main

import (
	"bufio"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

var line = regexp.MustCompile(`^\s*constexpr StringId (\w+) = (?:UNUSED_STR\()?(\d+)\)?;`)

func goName(s string) string {
	var b strings.Builder
	for _, p := range strings.Split(s, "_") {
		if p != "" {
			b.WriteString(strings.ToUpper(p[:1]) + p[1:])
		}
	}
	n := b.String()
	if n[0] >= '0' && n[0] <= '9' {
		n = "S" + n
	}
	return n
}

func main() {
	src := flag.String("openloco", "../OpenLoco", "the OpenLoco source tree")
	out := flag.String("out", "pkg/i18n/stringids.go", "the Go file to write")
	flag.Parse()
	f, err := os.Open(filepath.Join(*src, "src/OpenLoco/include/OpenLoco/Localisation/StringIds.h"))
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()
	var b strings.Builder
	b.WriteString("// Code generated by cmd/genstringids from OpenLoco's Localisation/StringIds.h. DO NOT EDIT.\n\npackage i18n\n\n")
	b.WriteString("// StringIds are OpenLoco's string ids (StringIds::<name>), the keys of the\n// language packs.\nconst (\n")
	seen, n := map[string]bool{}, 0
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		m := line.FindStringSubmatch(sc.Text())
		if m == nil {
			continue
		}
		name := goName(m[1])
		if seen[name] {
			log.Fatalf("two StringIds become %s", name)
		}
		seen[name] = true
		fmt.Fprintf(&b, "\t%s = %s\n", name, m[2])
		n++
	}
	b.WriteString(")\n")
	src2, err := format.Source([]byte(b.String()))
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src2, 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("%d string ids → %s", n, *out)
}
